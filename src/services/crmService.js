import { customBackendRequest } from './customBackendSession';
const send=(path,method='GET',data)=>customBackendRequest(path,{method,...(data?{body:JSON.stringify({data})}:{})});
export const getLeads=(search='')=>send(`/crm/leads?search=${encodeURIComponent(search)}`);
export const createLead=data=>send('/crm/leads','POST',data);
export const updateLead=(id,data)=>send(`/crm/leads/${encodeURIComponent(id)}`,'PATCH',data);
export const getDeals=()=>send('/crm/deals');
export const createDeal=data=>send('/crm/deals','POST',data);
export const updateDeal=(id,data)=>send(`/crm/deals/${encodeURIComponent(id)}`,'PATCH',data);
export const getTasks=()=>send('/crm/tasks');
export const createTask=data=>send('/crm/tasks','POST',data);
export const getCrmAnalytics=()=>send('/crm/analytics');
export const getCrmCustomers=(query={})=>send(`/crm/customers?${new URLSearchParams(query)}`);
export const getSegments=()=>send('/crm/segments');
export const saveSegment=data=>send('/crm/segments','POST',data);
export const getPipelineStages=()=>send('/crm/pipeline/stages');
export const savePipelineStages=(stages,renames={})=>send('/crm/pipeline/stages','PATCH',{stages,renames});
export const convertLead=id=>send(`/crm/leads/${encodeURIComponent(id)}/convert`,'POST',{});
export const addCustomerActivity=(id,data)=>send(`/crm/activity/${encodeURIComponent(id)}`,'POST',data);
export const getCustomerActivity=id=>send(`/crm/activity/${encodeURIComponent(id)}`);
export const updateTask=(id,data)=>send(`/crm/tasks/${encodeURIComponent(id)}`,'PATCH',data);
export const updateCustomerTags=(id,tags)=>send(`/crm/customers/${encodeURIComponent(id)}/tags`,'POST',{tags});
export const renameSegment=(id,name)=>send(`/crm/segments/${encodeURIComponent(id)}`,'PATCH',{name});
export const applySegment=id=>send(`/crm/segments/${encodeURIComponent(id)}/apply`,'POST',{});
export const deleteSegment=id=>customBackendRequest(`/crm/segments/${encodeURIComponent(id)}`,{method:'DELETE'});
export const editSegment=(id,data)=>send(`/crm/segments/${encodeURIComponent(id)}`,'PATCH',data);
